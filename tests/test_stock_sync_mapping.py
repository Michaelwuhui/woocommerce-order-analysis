def test_duplicate_confirmation_is_idempotent(mapped_system):
    s=mapped_system;report=scan(s);body=payload(report,2)
    a=s.call('/mapping-scans/'+report['id']+'/confirm','POST',body)
    body['items'].reverse()
    b=s.call('/mapping-scans/'+report['id']+'/confirm','POST',body)
    assert a.status_code==b.status_code==202 and a.get_json()==b.get_json()
    s.work()
    assert s.call('/mapping-scans/'+report['id']+'/confirm','POST',body).get_json()==a.get_json()
    assert len(s.sql('SELECT * FROM inv_site_sku_map WHERE site_id=2'))==2
    assert len(s.sql("SELECT * FROM stock_sync_work WHERE kind='mapping_confirm'"))==1


def test_expiry_during_remote_verification_prevents_save(mapped_system,monkeypatch):
    s=mapped_system;report=scan(s)
    r=s.call('/mapping-scans/'+report['id']+'/confirm','POST',payload(report))
    real_now=stock_sync_mapping.now
    def advance(_url):
        monkeypatch.setattr(stock_sync_mapping,'now',lambda:real_now()+timedelta(hours=2))
    s.http.on_get=advance;s.work()
    assert s.call('/mapping-confirmations/'+r.get_json()['id']).get_json()['status']=='failed'
    assert not s.sql('SELECT * FROM inv_site_sku_map WHERE site_id=2')


