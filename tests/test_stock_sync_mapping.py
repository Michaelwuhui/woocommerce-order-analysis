def scan(s, source=1, targets=None):
    r = s.call('/mapping-scans','POST',{'source_site_id':source,'target_scope':{'mode':'explicit_sites','site_ids':targets or [2]}})
    assert r.status_code == 202, r.get_json()
    id_ = r.get_json()['id']; s.work()
    return s.call('/mapping-scans/'+id_).get_json()


def payload(report, count=1):
    items = [i for i in report['items'] if i['site_id']==2 and i['state'] in ('suggested','review','unmatched')][:count]
    return {'items':[{'id':i['id'],'sku_id':i['proposed_sku_id'] or 1,'qty_per_item':1} for i in items],
            'reason':'fixture reviewed binding','reviewed':True}


def confirm(s, report, body=None):
    r = s.call('/mapping-scans/'+report['id']+'/confirm','POST',body or payload(report))
    assert r.status_code == 202, r.get_json()
    s.work()
    return s.call('/mapping-confirmations/'+r.get_json()['id']).get_json()


