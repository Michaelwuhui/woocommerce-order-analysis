def product(s, site, *, flavor='Cola Ice', name=None, sku=None):
    url = 'https://reference.test' if site == 1 else 'https://target.test'
    pid = site*1000+1
    p = s.http.products[f'{url}/wp-json/wc/v3/products/{pid}']
    p.update(name=name or f'Hifancy Dream 45000 Puffs - {flavor}',
             sku=sku if sku is not None else 'HIFANCY-DREAM-45000-PUFFS-'+flavor.replace(' ','-').upper())
    return p


def order(s, site, p, *, name=None, sku=None, variant=0):
    source = {1:'https://reference.test',2:'https://target.test',3:'https://outside.test'}[site]
    item = {'product_id':p['id'], 'variation_id':variant, 'name':name or p['name'], 'sku':p['sku'] if sku is None else sku,
            'private_customer_field':'MUST NOT LEAVE ORDER READER'}
    s.sql('INSERT INTO orders VALUES(?,?,?)', (source,dumps([item]),'2026-09-17T10:00:00'))


def auto_payload(report, ids=None):
    selected = [i for i in report['items'] if i.get('certain') and i['writable'] and i['state'] in ('new','align','suggested') and (ids is None or i['id'] in ids)]
    return {'reviewed':True,'reason':'Reviewed automatic product identity',
            'items':[{'id':i['id'],'sku_id':i['proposed_sku_id'],'qty_per_item':i['qty_per_item'],
                      **({'create_sku':True} if i['state']=='new' else {})} for i in selected]}


def test_new_product_shared_across_sites_has_one_master_and_no_stock(identities):
    s=identities
    for sid in (1,2):
        p=product(s,sid);order(s,sid,p)
    s.sql('DELETE FROM inv_site_sku_map WHERE wc_product_id IN (1001,2001)')
    report=scan(s);chosen=[i for i in report['items'] if i['id'] in ('1:1001:0','2:2001:0')]
    assert all(i['state']=='new' and i['certain'] for i in chosen)
    assert chosen[0]['new_sku']['sku_code']==chosen[1]['new_sku']['sku_code']
    assert len(s.sql('SELECT * FROM inv_skus'))==3
    body=auto_payload(report,{i['id'] for i in chosen})
    r=s.call('/mapping-scans/'+report['id']+'/confirm','POST',body);assert r.status_code==202
    s.work();result=s.call('/mapping-confirmations/'+r.get_json()['id']).get_json()
    assert result['complete'], result
    masters=s.sql("SELECT * FROM inv_skus WHERE sku_code LIKE 'CAT-%'");assert len(masters)==1
    sku=masters[0]
    assert sku['brand_id']==7 and sku['series_id'] and sku['puff_count']==45000 and sku['flavor']=='Cola Ice'
    assert s.sql('SELECT COUNT(*) AS n FROM inv_site_sku_map WHERE sku_id=?',(sku['id'],))[0]['n']==2
    assert s.sql('SELECT * FROM oms_sku_warehouses WHERE sku_id=?',(sku['id'],))[0]['warehouse_id']==1
    assert not s.sql('SELECT * FROM inv_stock WHERE sku_id=?',(sku['id'],)) and not s.http.puts
    assert s.call('/mapping-scans/'+report['id']+'/confirm','POST',body).get_json()==r.get_json()
    c=s.connect();mapping.apply(c,r.get_json()['id'],s.woo);c.close()
    assert len(s.sql("SELECT * FROM inv_skus WHERE sku_code LIKE 'CAT-%'"))==1
    # The resulting identities can be used by the actual cross-site planner.
    plan=s.plan('reference_status');assert any(i['decision']=='change' and i['sku_id']==sku['id'] for i in plan['items'])


