def test_long_brand_alias_does_not_consume_model_and_pack_quantity_is_preserved(identities):
    s=identities
    s.sql("INSERT INTO brands VALUES(8,'Stag Bar',?)", (dumps(['Stagbar 6in1 180000 Puffs']),))
    s.sql("INSERT INTO brands VALUES(9,'FIZZY',?)", (dumps(['FIZZY TWINS']),))
    c=s.connect();rules=identity.classification_rules(c);c.close()
    assert identity.profile('Stagbar 6in1 180000 Puffs - Black Edition','',[],rules)['model_key']=='6in1'
    assert identity.profile('FIZZY TWINS 50000 Puffs - Cola Ice','',[],rules)['model_key']=='twins'
    single=identity.profile('Hifancy Dream 45000 Puffs - Cola Ice','',[],rules)
    pack=identity.profile('Hifancy Dream 45000 Puffs - Cola Ice (10 pcs)','',[],rules)
    assert pack['base_key']==single['base_key'] and pack['quantity']==10


